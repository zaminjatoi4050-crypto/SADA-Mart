--changeset sadamart:001-core-security-and-settings
CREATE TABLE users (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(64) NOT NULL CONSTRAINT uq_users_username UNIQUE,
    full_name VARCHAR2(120) NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    role VARCHAR2(32) NOT NULL CONSTRAINT chk_users_role CHECK (role IN ('ADMIN', 'MANAGER', 'CASHIER')),
    active NUMBER(1) DEFAULT 1 NOT NULL CONSTRAINT chk_users_active CHECK (active IN (0, 1)),
    failed_attempts NUMBER(5) DEFAULT 0 NOT NULL,
    locked_until TIMESTAMP NULL,
    last_sign_in_at TIMESTAMP NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE audit_logs (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_username VARCHAR2(64) NOT NULL,
    actor_role VARCHAR2(32) NOT NULL,
    action_type VARCHAR2(64) NOT NULL,
    entity_type VARCHAR2(64) NOT NULL,
    entity_ref VARCHAR2(64) NULL,
    details VARCHAR2(1000) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE store_settings (
    setting_key VARCHAR2(64) PRIMARY KEY,
    setting_value VARCHAR2(500) NOT NULL,
    updated_by VARCHAR2(64) NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

--changeset sadamart:002-catalog-and-inventory
CREATE TABLE products (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR2(40) NOT NULL CONSTRAINT uq_products_sku UNIQUE,
    barcode VARCHAR2(40) NOT NULL CONSTRAINT uq_products_barcode UNIQUE,
    name VARCHAR2(160) NOT NULL,
    category VARCHAR2(80) NOT NULL,
    brand VARCHAR2(80) NOT NULL,
    cost_price NUMBER(14, 2) NOT NULL CONSTRAINT chk_products_cost CHECK (cost_price >= 0),
    selling_price NUMBER(14, 2) NOT NULL CONSTRAINT chk_products_price CHECK (selling_price >= 0),
    reorder_point NUMBER(10) DEFAULT 10 NOT NULL CONSTRAINT chk_products_reorder CHECK (reorder_point >= 0),
    active NUMBER(1) DEFAULT 1 NOT NULL CONSTRAINT chk_products_active CHECK (active IN (0, 1)),
    version NUMBER(19) DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE inventory_balances (
    product_id NUMBER(19) PRIMARY KEY CONSTRAINT fk_inv_product REFERENCES products(id),
    quantity_on_hand NUMBER(14, 3) DEFAULT 0 NOT NULL CONSTRAINT chk_inv_qty CHECK (quantity_on_hand >= 0),
    weighted_avg_cost NUMBER(14, 4) DEFAULT 0 NOT NULL CONSTRAINT chk_inv_wac CHECK (weighted_avg_cost >= 0),
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE stock_movements (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id NUMBER(19) NOT NULL CONSTRAINT fk_mov_product REFERENCES products(id),
    product_name VARCHAR2(160) NOT NULL,
    movement_type VARCHAR2(32) NOT NULL CONSTRAINT chk_mov_type CHECK (movement_type IN ('SALE', 'PO_RECEIPT', 'RETURN', 'ADJUSTMENT', 'COUNT_RECONCILE')),
    signed_quantity NUMBER(14, 3) NOT NULL CONSTRAINT chk_mov_nonzero CHECK (signed_quantity <> 0),
    unit_cost NUMBER(14, 4) NOT NULL,
    reference_code VARCHAR2(64) NOT NULL,
    actor_username VARCHAR2(64) NOT NULL,
    reason VARCHAR2(255) NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_stock_movements_prod ON stock_movements(product_id, created_at DESC);

--changeset sadamart:003-suppliers-purchases-customers
CREATE TABLE suppliers (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(160) NOT NULL CONSTRAINT uq_suppliers_name UNIQUE,
    contact_person VARCHAR2(120) NOT NULL,
    phone VARCHAR2(40) NOT NULL,
    email VARCHAR2(120) NULL,
    payable_balance NUMBER(14, 2) DEFAULT 0.00 NOT NULL,
    active NUMBER(1) DEFAULT 1 NOT NULL
);

CREATE TABLE purchase_orders (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_number VARCHAR2(40) NOT NULL CONSTRAINT uq_po_number UNIQUE,
    supplier_id NUMBER(19) NOT NULL CONSTRAINT fk_po_supplier REFERENCES suppliers(id),
    supplier_name VARCHAR2(160) NOT NULL,
    order_date DATE NOT NULL,
    status VARCHAR2(24) NOT NULL CONSTRAINT chk_po_status CHECK (status IN ('OPEN', 'PARTIAL', 'RECEIVED')),
    total_amount NUMBER(14, 2) NOT NULL,
    balance_due NUMBER(14, 2) NOT NULL,
    created_by VARCHAR2(64) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE purchase_order_lines (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id NUMBER(19) NOT NULL CONSTRAINT fk_pol_po REFERENCES purchase_orders(id),
    product_id NUMBER(19) NOT NULL CONSTRAINT fk_pol_product REFERENCES products(id),
    ordered_qty NUMBER(14, 3) NOT NULL CONSTRAINT chk_pol_oqty CHECK (ordered_qty > 0),
    received_qty NUMBER(14, 3) DEFAULT 0 NOT NULL CONSTRAINT chk_pol_rqty CHECK (received_qty >= 0),
    unit_cost NUMBER(14, 2) NOT NULL CONSTRAINT chk_pol_cost CHECK (unit_cost >= 0)
);

CREATE TABLE customers (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(160) NOT NULL,
    phone VARCHAR2(40) NOT NULL,
    email VARCHAR2(120) NULL,
    loyalty_tier VARCHAR2(32) DEFAULT 'Standard' NOT NULL,
    credit_limit NUMBER(14, 2) DEFAULT 0.00 NOT NULL,
    receivable_balance NUMBER(14, 2) DEFAULT 0.00 NOT NULL,
    last_purchase_date DATE NULL,
    active NUMBER(1) DEFAULT 1 NOT NULL
);

--changeset sadamart:004-shifts-sales-returns-expenses
CREATE TABLE cash_shifts (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_code VARCHAR2(40) NOT NULL CONSTRAINT uq_shift_code UNIQUE,
    cashier_username VARCHAR2(64) NOT NULL,
    opened_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    closed_at TIMESTAMP NULL,
    opening_float NUMBER(14, 2) NOT NULL,
    cash_sales NUMBER(14, 2) DEFAULT 0.00 NOT NULL,
    cash_refunds NUMBER(14, 2) DEFAULT 0.00 NOT NULL,
    cash_expenses NUMBER(14, 2) DEFAULT 0.00 NOT NULL,
    expected_cash NUMBER(14, 2) NOT NULL,
    actual_cash NUMBER(14, 2) NULL,
    variance NUMBER(14, 2) DEFAULT 0.00 NOT NULL,
    status VARCHAR2(24) NOT NULL CONSTRAINT chk_shift_status CHECK (status IN ('OPEN', 'RECONCILED'))
);

CREATE TABLE sales (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number VARCHAR2(40) NOT NULL CONSTRAINT uq_sales_invoice UNIQUE,
    idempotency_key VARCHAR2(80) NOT NULL CONSTRAINT uq_sales_idemp UNIQUE,
    cashier_username VARCHAR2(64) NOT NULL,
    customer_id NUMBER(19) NULL CONSTRAINT fk_sales_customer REFERENCES customers(id),
    shift_id NUMBER(19) NULL CONSTRAINT fk_sales_shift REFERENCES cash_shifts(id),
    subtotal NUMBER(14, 2) NOT NULL,
    line_discounts NUMBER(14, 2) NOT NULL,
    order_discount NUMBER(14, 2) NOT NULL,
    taxable_amount NUMBER(14, 2) NOT NULL,
    tax_percent NUMBER(7, 4) NOT NULL,
    tax_amount NUMBER(14, 2) NOT NULL,
    total_amount NUMBER(14, 2) NOT NULL,
    payment_summary VARCHAR2(64) NOT NULL,
    status VARCHAR2(24) DEFAULT 'COMPLETED' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE sale_lines (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id NUMBER(19) NOT NULL CONSTRAINT fk_sl_sale REFERENCES sales(id),
    product_id NUMBER(19) NOT NULL CONSTRAINT fk_sl_product REFERENCES products(id),
    product_sku VARCHAR2(40) NOT NULL,
    product_name VARCHAR2(160) NOT NULL,
    quantity NUMBER(14, 3) NOT NULL CONSTRAINT chk_sl_qty CHECK (quantity > 0),
    returned_quantity NUMBER(14, 3) DEFAULT 0 NOT NULL CONSTRAINT chk_sl_ret_qty CHECK (returned_quantity >= 0),
    unit_cost_at_sale NUMBER(14, 4) NOT NULL,
    unit_price NUMBER(14, 2) NOT NULL,
    line_discount NUMBER(14, 2) NOT NULL,
    line_total NUMBER(14, 2) NOT NULL
);

CREATE TABLE sale_payments (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id NUMBER(19) NOT NULL CONSTRAINT fk_sp_sale REFERENCES sales(id),
    payment_method VARCHAR2(32) NOT NULL,
    amount NUMBER(14, 2) NOT NULL CONSTRAINT chk_sp_amt CHECK (amount > 0)
);

CREATE TABLE sale_returns (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_number VARCHAR2(40) NOT NULL CONSTRAINT uq_return_number UNIQUE,
    original_sale_id NUMBER(19) NOT NULL CONSTRAINT fk_ret_sale REFERENCES sales(id),
    original_invoice VARCHAR2(40) NOT NULL,
    product_sku VARCHAR2(40) NOT NULL,
    returned_qty NUMBER(14, 3) NOT NULL CONSTRAINT chk_ret_qty CHECK (returned_qty > 0),
    original_unit_cost NUMBER(14, 4) NOT NULL,
    refund_amount NUMBER(14, 2) NOT NULL,
    reason VARCHAR2(255) NOT NULL,
    restocked NUMBER(1) DEFAULT 1 NOT NULL,
    actor_username VARCHAR2(64) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE expenses (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_code VARCHAR2(40) NOT NULL CONSTRAINT uq_expense_voucher UNIQUE,
    expense_date DATE NOT NULL,
    category VARCHAR2(80) NOT NULL,
    description VARCHAR2(255) NOT NULL,
    payment_method VARCHAR2(32) NOT NULL,
    amount NUMBER(14, 2) NOT NULL CONSTRAINT chk_expense_amt CHECK (amount > 0),
    status VARCHAR2(24) DEFAULT 'Approved' NOT NULL,
    approved_by VARCHAR2(64) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
